namespace Santase.Logic
{
    public enum PlayerPosition
    {
        /// <summary>
        /// No player: for example, no winner yet or a drawn round.
        /// </summary>
        NoOne = 0,

        /// <summary>
        /// The first player.
        /// </summary>
        FirstPlayer = 1,

        /// <summary>
        /// The second player.
        /// </summary>
        SecondPlayer = 2,
    }
}
